/*  Getters — keep components independent from the storage format.    */
/* ------------------------------------------------------------------ */

const today = () => new Date().toISOString().slice(0, 10);

export function getCourses() {
  return [...courses].sort((a, b) => a.order - b.order);
}

export function getCourse(slug: string) {
  return courses.find((c) => c.slug === slug) ?? null;
}

export function getFeaturedCourses() {
  return getCourses().filter((c) => c.featured);
}

/** Upcoming sessions (today or later), soonest first. */
export function upcomingSessions(course: Course, now = today()) {
  return course.sessions
    .filter((s) => (s.end ?? s.start) >= now)
    .sort((a, b) => a.start.localeCompare(b.start));
}

export function nextSession(course: Course) {
  return upcomingSessions(course)[0] ?? null;
}

export function courseCity(course: Course) {
  return nextSession(course)?.city ?? course.city;
}

export function relatedCourses(course: Course, limit = 3) {
  return getCourses()
    .filter((c) => c.slug !== course.slug)
    .map((c) => ({
      c,
      score: c.audiences.filter((a) => course.audiences.includes(a)).length,
    }))
    .sort((a, b) => b.score - a.score || a.c.order - b.c.order)
    .slice(0, limit)
    .map(({ c }) => c);
}
